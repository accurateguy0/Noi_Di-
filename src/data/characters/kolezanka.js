export function getKolezankaEncounter(index = null, heroId = null) {
  const hid = heroId ? String(heroId).toLowerCase() : null;
  if (hid && HERO_KOLEZANKA_SETS[hid]) {
    const sets = Array.isArray(HERO_KOLEZANKA_SETS[hid]) ? HERO_KOLEZANKA_SETS[hid] : [HERO_KOLEZANKA_SETS[hid]];
    const selectedIdx = (index !== null && index >= 0 && index < sets.length)
      ? index
      : Math.floor(Math.random() * sets.length);
    const data = sets[selectedIdx];
    return {
      type: 'girl_rank_order',
      titlePl: data.titlePl,
      subtitlePl: data.subtitlePl,
      icon: './assets/Postacie/kolezanka.png',
      enemyName: 'Koleżanka z klasy',
      enemyMaxHp: 26,
      enemyDamage: 3,
      descriptionPl: data.descriptionPl,
      steps: [...data.steps]
    };
  }
  const idx = (index !== null && index >= 0 && index < KOLEZANKA_SETS.length)
    ? index
    : Math.floor(Math.random() * KOLEZANKA_SETS.length);
  const data = KOLEZANKA_SETS[idx];
  return {
    type: 'girl_rank_order',
    titlePl: data.titlePl,
    subtitlePl: data.subtitlePl,
    icon: './assets/Postacie/kolezanka.png',
    enemyName: 'Koleżanka z klasy',
    enemyMaxHp: 26,
    enemyDamage: 3,
    descriptionPl: data.descriptionPl,
    steps: [...data.steps]
  };
}

