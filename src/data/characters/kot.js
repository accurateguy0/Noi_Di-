export function getKotWarmup(floor = 1, minigame = 'wheel', heroId = null) {
  const hid = heroId ? String(heroId).toLowerCase() : null;
  if (hid && KOT_HERO_WARMUPS[hid] && KOT_HERO_WARMUPS[hid][minigame]) {
    return KOT_HERO_WARMUPS[hid][minigame];
  }
  const f = Math.max(1, Math.min(5, Number(floor) || 1));
  const floorData = KOT_FLOOR_WARMUPS[f] || KOT_FLOOR_WARMUPS[1];
  return floorData[minigame] || floorData.wheel;
}

export const getCatWarmup = getKotWarmup;
