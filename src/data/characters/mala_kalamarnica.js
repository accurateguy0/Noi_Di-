export function getMalaKalamarnicaEncounter(index = null, heroId = null) {
  const hid = heroId ? String(heroId).toLowerCase() : null;
  if (hid && HERO_KALAMARNICA_SETS[hid]) {
    const sets = Array.isArray(HERO_KALAMARNICA_SETS[hid]) ? HERO_KALAMARNICA_SETS[hid] : [HERO_KALAMARNICA_SETS[hid]];
    const selectedIdx = (index !== null && index >= 0 && index < sets.length)
      ? index
      : Math.floor(Math.random() * sets.length);
    const data = sets[selectedIdx];
    return {
      type: 'squid_anagram',
      titlePl: data.titlePl,
      subtitlePl: data.subtitlePl,
      icon: './assets/Postacie/Mala_Kalamarnica.png',
      enemyName: 'Mała Kałamarnica',
      enemyMaxHp: 26,
      enemyDamage: 2,
      descriptionPl: data.descriptionPl,
      words: [...data.words]
    };
  }
  const idx = (index !== null && index >= 0 && index < KALAMARNICA_SETS.length)
    ? index
    : Math.floor(Math.random() * KALAMARNICA_SETS.length);
  const data = KALAMARNICA_SETS[idx];
  return {
    type: 'squid_anagram',
    titlePl: data.titlePl,
    subtitlePl: data.subtitlePl,
    icon: './assets/Postacie/Mala_Kalamarnica.png',
    enemyName: 'Mała Kałamarnica',
    enemyMaxHp: 26,
    enemyDamage: 2,
    descriptionPl: data.descriptionPl,
    words: [...data.words]
  };
}

