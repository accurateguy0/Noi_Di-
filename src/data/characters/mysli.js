export function getMysliEncounter(index = null, heroId = null) {
  const hid = heroId ? String(heroId).toLowerCase() : null;
  if (hid && HERO_MYSLI_SETS[hid]) {
    const sets = Array.isArray(HERO_MYSLI_SETS[hid]) ? HERO_MYSLI_SETS[hid] : [HERO_MYSLI_SETS[hid]];
    const selectedIdx = (index !== null && index >= 0 && index < sets.length)
      ? index
      : Math.floor(Math.random() * sets.length);
    const data = sets[selectedIdx];
    return {
      type: 'thoughts_tf',
      titlePl: data.titlePl,
      subtitlePl: data.subtitlePl,
      icon: './assets/Postacie/Mysli.png',
      enemyName: 'Wewnętrzne Myśli',
      enemyMaxHp: 42,
      enemyDamage: 5,
      descriptionPl: data.descriptionPl,
      questions: [...data.questions]
    };
  }
  const idx = (index !== null && index >= 0 && index < MYSLI_SETS.length)
    ? index
    : Math.floor(Math.random() * MYSLI_SETS.length);
  const data = MYSLI_SETS[idx];
  return {
    type: 'thoughts_tf',
    titlePl: data.titlePl,
    subtitlePl: data.subtitlePl,
    icon: './assets/Postacie/Mysli.png',
    enemyName: 'Wewnętrzne Myśli',
    enemyMaxHp: 42,
    enemyDamage: 5,
    descriptionPl: data.descriptionPl,
    questions: [...data.questions]
  };
}

